"""Golden tests for the commit-history neutrality lint (synthetic terms only)."""
import json
import unittest
from unittest import mock

from skillkit.core import lint_commits, lint_neutrality
from skillkit.core.scan import Scan
from tests.helpers import TempCase, run

TERMS = """\
[[terms]]
term = "zorblax"
mode = "word-ci"

[[terms]]
term = "Quux"
mode = "word-cs"
"""
RS, US = lint_commits.RS, lint_commits.US


def stream(commits=(), refs=()):
    out = ["C%s%s%s%s%s" % (US, cid, US, msg, RS) for cid, msg in commits]
    out += ["R%s%s%s%s%s" % (US, kind, US, name, RS) for kind, name in refs]
    return "\n".join(out)


class LintCommitsTests(TempCase):
    def setUp(self):
        super().setUp()
        (self.tmp / "policy").mkdir()
        (self.tmp / "policy" / "neutrality-terms.toml").write_text(TERMS, encoding="utf-8")

    def lint(self, **kw):
        return lint_commits.run(Scan(self.tmp), stream(**kw))

    def rules(self, **kw):
        found, _stats, ran = self.lint(**kw)
        self.assertTrue(ran)
        return sorted(f["rule"] for f in found)

    def test_clean_message(self):
        found, stats, ran = self.lint(commits=[("a" * 40, "router: add planner (S8)\n\nPlain body.\n")],
                                      refs=[("branch", "v2/g2-router"), ("tag", "g2-start")])
        self.assertTrue(ran)
        self.assertEqual(found, [])
        self.assertEqual(stats, {"commits": 1, "refs": 2})

    def test_term_in_subject_and_body(self):
        self.assertEqual(self.rules(commits=[("b" * 40, "fix zorblax handling\n\nand Quux too\n")]),
                         ["lint-commit-term", "lint-commit-term"])
        self.assertEqual(self.rules(commits=[("b" * 40, "fix quux handling\n")]), [])  # word-cs

    def test_attribution_trailer(self):
        msg = "core: change\n\nCo-Authored-By: Someone Else\n"
        self.assertEqual(self.rules(commits=[("c" * 40, msg)]), ["lint-commit-trailer"])
        self.assertEqual(self.rules(commits=[("c" * 40, "x\n\nco-authored-by:a\n")]), ["lint-commit-trailer"])

    def test_generated_line(self):
        for line in ("Generated with a tool", "\U0001f916 Generated by a tool", "generated with x"):
            self.assertEqual(self.rules(commits=[("d" * 40, "x\n\n%s\n" % line)]), ["lint-commit-generated"], line)
        self.assertEqual(self.rules(commits=[("d" * 40, "gen: regenerated with the new schema\n")]), [])

    def test_bad_ref_names(self):
        self.assertEqual(self.rules(refs=[("branch", "feature/zorblax-x")]), ["lint-ref-term"])
        self.assertEqual(self.rules(refs=[("tag", "Quux-1")]), ["lint-ref-term"])

    def test_malformed_stream_and_missing_policy(self):
        found, _s, ran = lint_commits.run(Scan(self.tmp), "garbage" + RS)
        self.assertTrue(ran)
        self.assertEqual([f["rule"] for f in found], ["lint-commit-input"])
        (self.tmp / "policy" / "neutrality-terms.toml").unlink()
        _f, _s, ran = lint_commits.run(Scan(self.tmp), "")
        self.assertFalse(ran)

    def test_cli_exit_codes_and_json(self):
        data = stream(commits=[("e" * 40, "zorblax fix\n")])
        with mock.patch("sys.stdin") as stdin:
            stdin.read.return_value = data
            code, out, _ = run("lint", "commits", "--stdin", "--root", str(self.tmp), "--format", "json")
        self.assertEqual(code, 1)
        self.assertEqual(json.loads(out)["summary"]["error"], 1)
        with mock.patch("sys.stdin") as stdin:
            stdin.read.return_value = stream(commits=[("e" * 40, "fine\n")])
            code, _o, _e = run("lint", "commits", "--stdin", "--root", str(self.tmp))
        self.assertEqual(code, 0)
        code, _o, err = run("lint", "commits", "--root", str(self.tmp))
        self.assertEqual(code, 2)


if __name__ == "__main__":
    unittest.main()
