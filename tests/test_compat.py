import re
import unittest
from unittest import mock

from skillkit.core import compat, generate
from tests.helpers import FIXTURES, TempCase, findings_of


class CompatOutputTests(TempCase):
    def outputs(self):
        return generate.evaluate(FIXTURES / "good", with_drift=False).outputs

    def test_expected_files(self):
        out = self.outputs()
        for rel in ("catalog.yaml", "INDEX.md", "capabilities.md", "guidance/INDEX.md",
                    "categories/meta.md", "categories/research.md"):
            self.assertIn(rel, out)

    def test_no_absolute_paths_or_crlf(self):
        needles = ["/" + "home" + "/", "/" + "mnt" + "/", "/" + "Users" + "/", "~" + "/.", "\r"]
        for rel, data in self.outputs().items():
            text = data.decode("utf-8")
            for needle in needles:
                self.assertNotIn(needle, text, (rel, needle))
            self.assertTrue(text.endswith("\n") and not text.endswith("\n\n"), rel)

    def test_catalog_yaml_shape(self):
        text = self.outputs()["catalog.yaml"].decode("utf-8")
        self.assertTrue(text.startswith("# Generated by"))
        self.assertIsNone(re.search(r"[&*]id\d+|\{[^}]|\[[^\]]", text))  # no anchors/aliases/flow collections
        self.assertIn('"disable-model-invocation": false', text)
        # pointer entries keep upstream/install/summary and mirror upstream as source
        self.assertIn('"upstream":', text)
        self.assertIn('"install":', text)

    def test_index_lists_categories_and_uses_variables(self):
        text = self.outputs()["INDEX.md"].decode("utf-8")
        self.assertIn("`categories/research.md`", text)
        self.assertIn("$AI_TOOLS_ROOT/skills/installed/", text)

    def test_category_rows_are_sorted_with_relative_links(self):
        text = self.outputs()["categories/research.md"].decode("utf-8")
        self.assertIn("](../skills/", text)
        ids = re.findall(r"^\| \[([^\]]+)\]", text, re.M)
        self.assertEqual(ids, sorted(ids))

    def test_router_surface_budget(self):
        self.assertEqual(compat.INDEX_MD, "INDEX.md")
        root = self.copy_fixture("good")
        self.assertEqual([f for f in findings_of(root)[1] if f["rule"] == "router-surface"], [])
        with mock.patch.object(generate, "ROUTER_SURFACE_BUDGET", 10):
            _, found = findings_of(root)
        self.assertEqual([f["rule"] for f in found if f["severity"] == "error"], ["router-surface"])
        with mock.patch.object(generate, "ROUTER_INDEX_BUDGET", 10):
            _, found = findings_of(root)
        self.assertIn("router-surface", [f["rule"] for f in found])


if __name__ == "__main__":
    unittest.main()
