"""Compat outputs (spec D6): catalog.yaml, INDEX.md, categories/*.md,
capabilities.md and guidance/INDEX.md, derived from the same normalised
catalog entries as registry/*.json. Removed at P3.

Pure functions: entries in, {relpath: bytes} out. Text carries no absolute
paths; runtime locations use the `$AI_TOOLS_ROOT` variable.
"""
from . import yamlout

CATALOG_YAML = "catalog.yaml"
INDEX_MD = "INDEX.md"
CAPABILITIES_MD = "capabilities.md"
GUIDANCE_INDEX_MD = "guidance/INDEX.md"
CATEGORY_DIR = "categories"
CATALOG_SCHEMA_VERSION = 2

_RUNTIME_DIR = {"guidance": "guidance", "workflow": "workflows", "plugin": "plugins"}


def _catalog_entry(e):
    r = e["routing"]
    out = {
        "id": e["id"],
        "name": e["name"],
        "description": e["description"],
        "type": e["type"],
        "category": e["category"],
        "capabilities": list(r["provides"]),
        "path": e["path"],
        "activation": e["activation"],
        "requires": list(r["requires"]),
        "conflicts": list(r["conflicts_with"]),
        "risk": e["risk"],
        "priority": e["priority"],
    }
    if "disable-model-invocation" in e:
        out["disable-model-invocation"] = e["disable-model-invocation"]
    manifest = e.get("manifest")
    if manifest is not None:
        out["upstream"] = dict(manifest.get("upstream", {}))
        out["install"] = dict(manifest.get("install", {}))
        out["summary"] = manifest.get("summary", "")
        if manifest.get("notes"):
            out["notes"] = manifest["notes"]
        out["source"] = dict(manifest.get("upstream", {}))
    else:
        out["source"] = dict(e["provenance"])
    return out


def catalog_yaml(entries):
    data = {"schema_version": CATALOG_SCHEMA_VERSION,
            "skills": [_catalog_entry(e) for e in entries]}
    return "# Generated by skillkit gen - do not hand-edit.\n" + yamlout.dumps(data, sort_keys=False)


def _title(category):
    return category.replace("-", " ").title()


def index_md(entries):
    categories = sorted({e["category"] for e in entries})
    lines = [
        "# tisserand registry index",
        "",
        "Read this compact routing index before non-trivial work.",
        "Do not load every asset.",
        "",
        "## Rules",
        "",
        "1. Match the task to a category first.",
        "2. Load only the smallest relevant skill set.",
        "3. `explicit` / `manual` skills are never inferred unless requested.",
        "4. `contextual` capabilities may be selected when the task clearly matches.",
        "5. `skill-router` is the only always-on routing skill.",
        "6. Guidance, workflows, and plugins are capability pointers, not skill prompts.",
        "7. Use `capabilities.md` for non-skill capability lookup.",
        "8. Never recursively search the repository for routine capability discovery.",
        "",
        "## Categories",
        "",
    ]
    for category in categories:
        lines.append("- **%s** → `categories/%s.md`" % (_title(category), category))
    lines += [
        "",
        "## Capability layer",
        "",
        "Use `capabilities.md` for guidance, workflow, and plugin routing.",
        "Use `$AI_TOOLS_ROOT/guidance/INDEX.md` for coding/task guidance.",
        "",
        "## Canonical curation and exposure",
        "",
        "Authored curated source: `$AI_TOOLS_ROOT/tisserand/skills/`.",
        "Generated shared runtime: `$AI_TOOLS_ROOT/skills/installed/`; do not hand-edit it.",
        "Harness skill roots are thin links to that runtime where supported.",
        "Externally derived copies in user-level skill roots are separate; do not auto-promote, overwrite, or remove them.",
        "Skills use standard `SKILL.md` metadata and are installed into Agent Skills-compatible global locations.",
        "",
        "## Runtime",
        "",
        "`$AI_TOOLS_ROOT` is the durable local AI-tools root.",
        "Skills: `$AI_TOOLS_ROOT/skills/installed/`",
        "Guidance: `$AI_TOOLS_ROOT/guidance/`",
        "Workflows: `$AI_TOOLS_ROOT/workflows/`",
        "Plugins: `$AI_TOOLS_ROOT/plugins/`",
    ]
    return "\n".join(lines) + "\n"


def _category_link(e):
    if e["type"] == "skill":
        return "../skills/%s/SKILL.md" % e["id"]
    if e["type"] == "guidance":
        return "../guidance/%s/GUIDANCE.md" % e["id"]
    return "../%s/%s/manifest.yaml" % (_RUNTIME_DIR[e["type"]], e["id"])


def category_md(category, members):
    lines = [
        "# %s" % _title(category),
        "",
        "| Asset | Type | Activation | Capabilities | Description |",
        "|---|---|---|---|---|",
    ]
    for e in sorted(members, key=lambda x: x["id"]):
        lines.append("| [%s](%s) | %s | %s | %s | %s |" % (
            e["id"], _category_link(e), e["type"], e["activation"],
            ", ".join(e["routing"]["provides"]), e["description"]))
    return "\n".join(lines) + "\n"


def capabilities_md(entries):
    lines = [
        "# Capability Pointers",
        "",
        "This file is intentionally compact.",
        "Use it to identify external guidance, workflows, and plugins.",
        "Do not recursively search the repository for capability discovery.",
        "",
        "| ID | Type | Capability | Runtime location |",
        "|---|---|---|---|",
    ]
    for e in entries:
        if e["type"] == "skill":
            continue
        runtime = "$AI_TOOLS_ROOT/%s/%s/" % (_RUNTIME_DIR[e["type"]], e["id"])
        lines.append("| `%s` | `%s` | %s | `%s` |" % (
            e["id"], e["type"], ", ".join(e["routing"]["provides"]), runtime))
    lines += [
        "",
        "## Runtime rules",
        "",
        "- `skill`: loaded by the Agent Skills mechanism.",
        "- `guidance`: task-selected reference material; load only when relevant.",
        "- `workflow`: external development system; inspect its manifest and runtime command.",
        "- `plugin`: external integration; inspect its manifest and runtime installation.",
        "- Never confuse registration with installation.",
    ]
    return "\n".join(lines) + "\n"


def guidance_index_md(entries):
    lines = [
        "# Guidance Index",
        "",
        "Guidance is selected automatically when its task triggers match.",
        "Do not load all guidance by default.",
        "",
        "| Guidance | Trigger | Path |",
        "|---|---|---|",
    ]
    for e in entries:
        if e["type"] != "guidance":
            continue
        lines.append("| `%s` | %s | `%s` |" % (e["id"], ", ".join(e["routing"]["provides"]), e["path"]))
    return "\n".join(lines) + "\n"


def build(entries):
    """entries: normalised catalog entries sorted by id. Returns {relpath: bytes}."""
    texts = {
        CATALOG_YAML: catalog_yaml(entries),
        INDEX_MD: index_md(entries),
        CAPABILITIES_MD: capabilities_md(entries),
        GUIDANCE_INDEX_MD: guidance_index_md(entries),
    }
    by_category = {}
    for e in entries:
        by_category.setdefault(e["category"], []).append(e)
    for category, members in by_category.items():
        texts["%s/%s.md" % (CATEGORY_DIR, category)] = category_md(category, members)
    return {rel: text.encode("utf-8") for rel, text in texts.items()}
