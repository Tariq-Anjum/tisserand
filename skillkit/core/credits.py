"""Deterministic attribution data; never imply clearance from legacy metadata.

sources/notices.toml may hold [[notice]] records with evidence_ref and text.
Those exact notices are retained even after a capability becomes independent:
historical distribution obligations do not expire with a rewrite.
"""
import re

from . import tomlio

DATA_PATHS = frozenset(('CREDITS.md', 'THIRD_PARTY_NOTICES'))
NOTICES = 'sources/notices.toml'


def _cell(value):
    return str(value).replace('|', '&#124;').replace('\r', '').replace('\n', '<br>')


def _row(values):
    return '| ' + ' | '.join(_cell(v or 'UNKNOWN') for v in values) + ' |'


def build(entries, sources):
    lines = ['<!-- Generated by skillkit gen; provenance data; do not edit. -->', '', '# Credits', '',
             'Disposition key: INDEPENDENT = compared with the named upstream, no shared',
             '8-gram found (an overlap check, not licence clearance); ORIGINAL = our text,',
             'mechanisms from idea cards; LEGACY-UNATTESTED = our earlier text, origin not',
             'attested, not cleared; UNKNOWN = not analysed, not cleared.', '',
             '| Capability | Inspiration | URL | SHA | Licence | Date | Disposition | Evidence |',
             '|---|---|---|---|---|---|---|---|']
    notes, used_cards = [], set()
    def title(rel):
        text = sources.get(rel, b'').decode('utf-8')
        return next((s[2:].strip() for s in text.splitlines() if s.startswith('# ')), 'UNKNOWN')
    registry = tomlio.loads(sources.get('sources/idea-cards.toml', b'').decode('utf-8'))
    cards = {i: c for c in registry.get('card', []) for i in c['ids']}
    attestations = {r['path']: r for r in registry.get('text', [])}
    notices = tomlio.loads(sources.get(NOTICES, b'').decode('utf-8')).get('notice', [])
    by_evidence = {}
    for notice in notices:
        if (not isinstance(notice, dict) or set(notice) != {'evidence_ref', 'text'}
                or not isinstance(notice['text'], str) or not notice['text'].strip()
                or not isinstance(notice['evidence_ref'], str)
                or not re.fullmatch(r'ev:lic:[a-z0-9][a-z0-9.-]{0,62}', notice['evidence_ref'])
                or notice['evidence_ref'] in by_evidence):
            raise ValueError('notices need unique relative evidence_ref and nonempty exact text')
        by_evidence[notice['evidence_ref']] = notice['text']
    required = []
    for e in sorted(entries, key=lambda e: e['id']):
        p = e['provenance']
        disposition = p.get('disposition', 'UNKNOWN')
        inspirations = p.get('inspired_by') or [dict(name=p.get('derived_from') or p.get('source') or 'UNKNOWN',
            url=p.get('source', ''), sha=p.get('ref', ''), licence=p.get('license', ''), date=p.get('verified', ''))]
        ids = attestations.get(e.get('path'), {}).get('idea_cards', [])
        used_cards.update(ids)
        own = disposition in ('ORIGINAL', 'LEGACY-UNATTESTED')
        if own:
            inspirations = [dict(name='own text', url='n/a', sha='n/a', licence=p.get('license'), date=p.get('verified'))]
        for source in inspirations:
            lines.append(_row([e['id'], source.get('name'), source.get('url'), source.get('sha'),
                source.get('licence'), source.get('date'), disposition, 'n/a' if own else p.get('evidence_ref')]))
        card_labels = '; '.join('%s (%s)' % (i, title(cards.get(i, {}).get('source_record', ''))) for i in ids)
        if disposition == 'INDEPENDENT':
            notes.append('%s: inspired by (mechanism only) %s; compared, no text copied (%s).' % (
                e['id'], '; '.join(str(x.get('name', 'UNKNOWN')) for x in inspirations), p.get('evidence_ref', 'UNKNOWN')))
            if ids:
                notes.append('Other mechanisms (mechanism only): %s.' % card_labels)
        elif disposition == 'ORIGINAL':
            notes.append(('%s: our text, written from idea cards, not from upstream text. Inspired by (mechanism only): %s.' % (e['id'], card_labels))
                         if ids else '%s: our text; no outside source.' % e['id'])
        elif disposition == 'LEGACY-UNATTESTED':
            notes.append('%s: earlier registry text; origin not attested; no upstream compare run; not cleared.' % e['id'])
        elif disposition == 'UNKNOWN':
            notes.append('%s: not analysed; not cleared.' % e['id'])
            if ids:
                notes.append('Inspired by (mechanism only): %s.' % card_labels)
        else:
            notes.append('%s: %s; see THIRD_PARTY_NOTICES.' % (e['id'], disposition))
        details = e.get('routing', {}).get('provides', [])
        if e.get('path') or details:
            notes.append('%s (%s): %s.' % (e['id'], e.get('path', 'UNKNOWN'), '; '.join(details)))
        notes.append('')
        if disposition.startswith('COPIED-'):
            ref = p.get('evidence_ref')
            if ref not in by_evidence:
                raise ValueError('%s: required upstream notice missing from %s' % (e['id'], NOTICES))
            required.append((e['id'], disposition, ref, inspirations))
    lines += ['', '## Notes', ''] + notes
    lines += ['## Idea-card sources', '']
    families = {}
    for ident in sorted(used_cards):
        rel = cards.get(ident, {}).get('source_record', 'UNKNOWN')
        families.setdefault(rel, []).append(ident)
    for rel, ids in sorted(families.items()):
        lines.append('- %s: %s (%s).' % (', '.join(ids), title(rel), rel))
    lines += ['', '## Source records', '']
    for rel, data in sorted(sources.items()):
        if not rel.endswith('.md'):
            continue
        text = data.decode('utf-8')
        title = next((s[2:].strip() for s in text.splitlines() if s.startswith('# ')), rel)
        url = next((s.split(':', 1)[1].strip() for s in text.splitlines() if s.startswith('Repo:')), 'UNKNOWN')
        licence = next((s.split(':', 1)[1].strip() for s in text.splitlines() if s.startswith('License:')), 'UNKNOWN')
        lines.append('- %s: %s; URL %s; licence %s.' % (rel, title, url, licence))
    notice_lines = ['Generated by skillkit gen; provenance data; do not edit.', '',
                    'THIRD PARTY NOTICES', '',
                    'Required upstream notices are retained for distributed copies, including history.', '']
    for ident, disposition, ref, inspirations in required:
        notice_lines += ['Capability: %s (%s)' % (ident, disposition), 'Evidence: ' + ref]
        for source in inspirations:
            notice_lines.append(' | '.join(str(source.get(k, 'UNKNOWN')) for k in ('name', 'url', 'sha', 'licence', 'date')))
        notice_lines.append('')
    for ref, text in sorted(by_evidence.items()):
        notice_lines += ['Evidence: ' + ref, text.rstrip(), '']
    if not by_evidence:
        notice_lines += ['No upstream notice text registered yet. UNKNOWN entries are not cleared.', '']
    return {'CREDITS.md': ('\n'.join(lines).rstrip() + '\n').encode('utf-8'),
            'THIRD_PARTY_NOTICES': ('\n'.join(notice_lines).rstrip() + '\n').encode('utf-8')}
