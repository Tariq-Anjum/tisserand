"""Commit-history neutrality lint (RULES K.1): commit messages, trailers and
branch/tag names never name a harness, agent or model/provider, and never
carry an attribution trailer.

Pure text function: the core spawns no process. `scripts/lint-commits.sh`
feeds it the VCS output in this stream format (records end with U+001E,
fields are separated by U+001F):

    C <sep> <commit id> <sep> <full message>
    R <sep> <kind: branch|tag> <sep> <ref name>

Rules (all errors):
  lint-commit-term         a policy/neutrality-terms.toml term in a message
  lint-commit-trailer      any `Co-Authored-By:` trailer line
  lint-commit-generated    a `Generated with` / `Generated by` line
  lint-ref-term            a term in a branch or tag name
"""
import re

from . import lint_neutrality
from .model import finding

RS, US = "\x1e", "\x1f"
TRAILER = re.compile(r"^[ \t]*co-authored-by[ \t]*:", re.I)
GENERATED = re.compile(r"^\W*generated[ \t]+(?:with|by)\b", re.I)
REF_KINDS = ("branch", "tag")


def parse_stream(text):
    """Return (commits [(id, message)], refs [(kind, name)], problems [str])."""
    commits, refs, problems = [], [], []
    for n, record in enumerate(text.split(RS), 1):
        record = record.lstrip("\n")
        if not record.strip():
            continue
        parts = record.split(US)
        if parts[0] == "C" and len(parts) == 3 and parts[1].strip():
            commits.append((parts[1].strip(), parts[2]))
        elif parts[0] == "R" and len(parts) == 3 and parts[1] in REF_KINDS and parts[2].strip():
            refs.append((parts[1], parts[2].strip()))
        else:
            problems.append("record %d is not a valid C/R record" % n)
    return commits, refs, problems


def check(config, commits, refs):
    """Findings for parsed commits and refs using a neutrality Config."""
    out = []
    for cid, message in commits:
        short = cid[:12]
        for n, line in enumerate(message.split("\n"), 1):
            where = "subject" if n == 1 else "body line %d" % n
            if TRAILER.search(line):
                out.append(finding(short, "lint-commit-trailer", "error", "commit",
                                   "%s: Co-Authored-By trailer is not allowed" % where))
            if GENERATED.search(line):
                out.append(finding(short, "lint-commit-generated", "error", "commit",
                                   "%s: 'Generated with/by' line is not allowed" % where))
            for term in lint_neutrality._hits(config, line):
                out.append(finding(short, "lint-commit-term", "error", "commit",
                                   "%s: names a specific harness/agent/model ('%s')" % (where, term)))
    for kind, name in refs:
        for term in lint_neutrality._hits(config, name):
            out.append(finding("", "lint-ref-term", "error", "%s:%s" % (kind, name),
                               "%s name contains a specific harness/agent/model ('%s')" % (kind, term)))
    return out


def run(scan, stream_text):
    """Return (findings, stats, ran). `ran` is False when the term policy is
    missing or invalid (findings then describe the configuration problem)."""
    report = lint_neutrality.Report()
    config = lint_neutrality.load_config(scan, report)
    if config is None:
        return list(report.problems), {}, False
    commits, refs, problems = parse_stream(stream_text)
    out = [finding("", "lint-commit-input", "error", "stdin", p) for p in problems]
    out += check(config, commits, refs)
    out.sort(key=lambda f: (f["path"], f["rule"], f["id"], f["msg"]))
    return out, {"commits": len(commits), "refs": len(refs)}, True
